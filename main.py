# Практическая работа №3
# Основы программирования на Python
# Вариант №9 — «Трёхзначное число»
#
# Назначение программы:
# Найти сумму и произведение цифр введённого трёхзначного числа.
#
# Входные данные:
# n — трёхзначное целое положительное число.
#
# Используемые операции:
# // — целочисленное деление;
# %  — получение остатка от деления.
#
# Формулы:
# a = n // 100          — первая цифра (сотни);
# b = (n // 10) % 10    — вторая цифра (десятки);
# c = n % 10            — третья цифра (единицы);
# total = a + b + c     — сумма цифр;
# product = a * b * c   — произведение цифр.


# Запрашиваем число у пользователя и преобразуем введённую строку в целое число.
n = int(input("Введите трёхзначное число: "))

# Получаем первую цифру числа — количество сотен.
a = n // 100

# Получаем вторую цифру числа — количество десятков.
b = (n // 10) % 10

# Получаем третью цифру числа — цифру единиц.
c = n % 10

# Складываем все три цифры.
total = a + b + c

# Перемножаем все три цифры.
product = a * b * c

# Выводим сумму цифр на экран.
print(f"Сумма цифр: {total}")

# Выводим произведение цифр на экран.
print(f"Произведение цифр: {product}")
